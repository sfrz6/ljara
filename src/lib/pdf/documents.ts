function head(l: L, orgName: string, orgNameAr: string | null, sub: string, title: string, meta: string): string {
  const name = l === "ar" ? orgNameAr || orgName : orgName;
  return `<div class="head"><div class="brand">${MARK}<div><b>${esc(name)}</b><span><bdi class="n">${esc(sub)}</bdi></span></div></div><div class="doc"><h1>${esc(title)}</h1><p>${meta}</p></div></div>`;
}

export function receiptHtml(r: { displayNumber: string; kind: "receipt" | "credit_note"; status: "issued" | "voided"; amountBaisa: number; snapshot: ReceiptSnapshot; issuedAt: Date; voidReason: string | null; relatedNumber: string | null }, l: L): string {
  const s = r.snapshot;
  const name = (en: string, ar: string | null) => esc(l === "ar" ? ar || en : en);
  const title = lab(r.kind === "receipt" ? "receipt" : "credit_note", l);
  const method = METHODS[s.method]?.[l] ?? s.method;
  const chq = s.chequeNumber ? `${lab("cheque", l)} <bdi class="n">#${esc(s.chequeNumber)}</bdi> ${esc(s.bank)}` : esc(s.reference ?? "");
  const body = `
${r.status === "voided" ? `<div class="stamp">${lab("voided", l)}</div>` : ""}
${head(l, s.orgName, s.orgNameAr, s.orgPhone ?? "", title, `${lab("number", l)}: <b><bdi class="n">${esc(r.displayNumber)}</bdi></b><br>${lab("date", l)}: ${formatDate(r.issuedAt, l)}`)}
<div class="grid">
  <div><span class="k">${lab("received_from", l)}</span><span class="v">${name(s.tenantName, s.tenantNameAr)}</span></div>
  <div><span class="k">${lab("owner", l)}</span><span class="v">${name(s.ownerName, s.ownerNameAr)}</span></div>
  <div><span class="k">${lab("property", l)}</span><span class="v">${name(s.buildingName, s.buildingNameAr)}</span></div>
  <div><span class="k">${lab("unit", l)}</span><span class="v">${esc(s.unitLabel)}</span></div>
  <div><span class="k">${lab("contract", l)}</span><span class="v"><bdi class="n">${esc(s.contractReference)}</bdi></span></div>
  <div><span class="k">${lab("for_period", l)}</span><span class="v">${formatDate(s.periodLabelDate, l)}</span></div>
  <div><span class="k">${lab("method", l)}</span><span class="v">${esc(method)}</span></div>
  <div><span class="k">${lab("reference", l)}</span><span class="v">${chq || "-"}</span></div>
</div>
<div class="box"><span class="k">${lab("amount", l)}</span><div class="amount">${r.kind === "credit_note" ? "-" : ""}${money(r.amountBaisa, l)}</div></div>
${r.kind === "credit_note" ? `<p>${lab("reverses", l)} <b><bdi class="n">${esc(r.relatedNumber ?? "")}</bdi></b>. ${lab("reason", l)}: ${esc(r.voidReason)}</p>` : ""}
${r.status === "voided" && r.voidReason ? `<p>${lab("reason", l)}: ${esc(r.voidReason)}</p>` : ""}
<p class="note">${lab("thanks", l)}</p>
<div class="foot"><span>${lab("generated", l)}</span><span><bdi class="n">${esc(r.displayNumber)}</bdi></span></div>`;
  return page(l, `${title} ${r.displayNumber}`, body);
}

export function statementHtml(st: { number: string; generatedAt: Date; snapshot: StatementSnapshot }, l: L): string {
  const s = st.snapshot;
  const t = s.totals;
  const pn = (en: string, ar: string | null) => esc(l === "ar" ? ar || en : en);
  const rentRows = s.rentLines.length
    ? s.rentLines.map((x) => `<tr><td>${formatDate(x.paidOn, l)}</td><td>${esc(x.unit)} · ${pn(x.building, x.buildingAr)}</td><td>${pn(x.tenant, x.tenantAr)}</td><td><bdi class="n">${esc(x.receiptNumber ?? "")}</bdi></td><td>${esc(METHODS[x.method]?.[l] ?? x.method)}</td><td class="e">${money(x.amountBaisa, l)}</td></tr>`).join("")
    : `<tr><td colspan="6">${lab("none", l)}</td></tr>`;
  const maintRows = s.maintenanceLines.length
    ? s.maintenanceLines.map((x) => `<tr><td>${formatDate(x.completedOn, l)}</td><td>${esc(x.unit)} · ${pn(x.building, x.buildingAr)}</td><td>${pn(x.category, x.categoryAr)}</td><td>${esc(x.work)}<br><span class="k"><bdi class="n">${esc(x.reference)}</bdi></span></td><td class="e">${money(x.costBaisa, l)}</td></tr>`).join("")
    : `<tr><td colspan="5">${lab("none", l)}</td></tr>`;
  const cats = s.maintenanceByCategory.map((c) => `<tr><td>${pn(c.name, c.nameAr)}</td><td class="e"><bdi class="n">${c.count}</bdi></td><td class="e">${money(c.totalBaisa, l)}</td></tr>`).join("");
  const negative = t.netToOwnerBaisa < 0;
  const body = `
${head(l, s.org.name, s.org.nameAr, [s.org.phone, s.org.email].filter(Boolean).join("  ·  "), lab("statement", l), `${lab("statement_no", l)}: <b><bdi class="n">${esc(st.number)}</bdi></b><br>${lab("period", l)}: ${formatDate(s.period.from, l)} - ${formatDate(s.period.to, l)}`)}
<div class="grid">
  <div><span class="k">${lab("owner", l)}</span><span class="v">${pn(s.owner.nameEn, s.owner.nameAr)}</span></div>
  <div><span class="k">${lab("commission", l)}</span><span class="v"><bdi class="n">${bpToPercentString(s.owner.commissionBp)}%</bdi></span></div>
</div>
<h2>${lab("summary", l)}</h2>
<table class="sum"><tbody>
<tr><td>${lab("rent_collected", l)}</td><td class="e">${money(t.rentCollectedBaisa, l)}</td></tr>
<tr><td>${lab("maintenance", l)}</td><td class="e">- ${money(t.maintenanceBaisa, l)}</td></tr>
<tr><td>${lab("mgmt_fee", l)} (<bdi class="n">${bpToPercentString(s.owner.commissionBp)}%</bdi>)</td><td class="e">- ${money(t.managementFeeBaisa, l)}</td></tr>
${t.gatewayFeeLineBaisa ? `<tr><td>${lab("gateway_fee", l)}</td><td class="e">- ${money(t.gatewayFeeLineBaisa, l)}</td></tr>` : ""}
${s.vat.enabled ? `<tr><td>${lab("vat", l)}</td><td class="e">- ${money(t.vatOnFeeBaisa, l)}</td></tr>` : ""}
<tr class="net"><td>${lab(negative ? "net_negative" : "net", l)}</td><td class="e">${money(Math.abs(t.netToOwnerBaisa), l)}</td></tr>
</tbody></table>
<h2>${lab("rent_details", l)}</h2>
<table><thead><tr><th>${lab("date", l)}</th><th>${lab("unit", l)}</th><th>${lab("tenant", l)}</th><th>${lab("receipt_no", l)}</th><th>${lab("method", l)}</th><th class="e">${lab("amount", l)}</th></tr></thead><tbody>${rentRows}</tbody></table>
<h2>${lab("maint_details", l)}</h2>
<table><thead><tr><th>${lab("date", l)}</th><th>${lab("unit", l)}</th><th>${lab("type", l)}</th><th>${lab("work", l)}</th><th class="e">${lab("amount", l)}</th></tr></thead><tbody>${maintRows}</tbody></table>
${cats ? `<h2>${lab("by_type", l)}</h2><table><thead><tr><th>${lab("type", l)}</th><th class="e">${lab("count", l)}</th><th class="e">${lab("total", l)}</th></tr></thead><tbody>${cats}</tbody></table>` : ""}
<p class="note">${lab("security_note", l)}</p>
<div class="foot"><span>${lab("generated", l)} · ${formatDate(st.generatedAt, l)}</span><span><bdi class="n">${esc(st.number)}</bdi></span></div>`;
  return page(l, `${lab("statement", l)} ${st.number}`, body);
}
