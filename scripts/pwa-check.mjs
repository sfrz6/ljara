import { chromium } from "@playwright/test";
const base = "http://localhost:3202";
const browser = await chromium.launch({ channel: "msedge" });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 } });
const page = await ctx.newPage();
await page.goto(base + "/login");
const manifestHref = await page.getAttribute('link[rel="manifest"]', "href");
const manifest = await (await page.request.get(base + manifestHref)).json();
console.log("manifest", manifest.name, manifest.display, manifest.start_url, manifest.icons.map((i) => `${i.sizes}:${i.purpose}`).join(","));
for (const i of manifest.icons) console.log("icon", i.src, (await page.request.get(base + i.src)).status());
console.log("apple-touch-icon", await page.getAttribute('link[rel="apple-touch-icon"]', "href"), "theme", await page.getAttribute('meta[name="theme-color"]', "content"));
console.log("apple-capable", await page.locator('meta[name="apple-mobile-web-app-capable"]').count());
console.log("viewport", await page.getAttribute('meta[name="viewport"]', "content"));
await page.evaluate(() => navigator.serviceWorker.ready);
const sw = await page.evaluate(async () => { const r = await navigator.serviceWorker.getRegistration(); return { scope: r?.scope, active: !!r?.active }; });
console.log("service worker", JSON.stringify(sw));
await page.reload(); await page.waitForTimeout(1500);
await ctx.setOffline(true);
await page.goto(base + "/dashboard").catch(() => {});
console.log("offline page text:", (await page.locator("body").innerText()).replace(/\n+/g, " | ").slice(0, 120));
await browser.close();
